_TOKEN = re.compile(r"^(\W*)(.+?)(\W*)$", re.UNICODE)


def spell_token(core: str) -> str | None:
    """Возвращает произносимую форму для сокращения или None, если менять не нужно."""
    if core in KNOWN:
        return KNOWN[core]
    if 2 <= len(core) <= 5 and core.isupper():
        if all(ch in CYR_LETTERS for ch in core):
            return "-".join(CYR_LETTERS[ch] for ch in core)
        if all(ch in LAT_LETTERS for ch in core):
            return "-".join(LAT_LETTERS[ch] for ch in core)
    return None


def normalize_for_tts(text: str) -> str:
    out = []
    for tok in text.split():
        m = _TOKEN.match(tok)
        if not m:
            out.append(tok)
            continue
        pre, core, post = m.groups()
        # склоняемые формы вроде "ИИ-модель" или "НАСА" с дефисом обрабатываем по частям
        parts = core.split("-")
        spoken = [spell_token(pt) or pt for pt in parts]
        out.append(pre + " ".join(spoken) + post)
    return " ".join(out)
